def test_all_hybrid_variants():
    passed = 0
    failed = 0
    print("=" * 80)
    print("K-Car 하이브리드 전 차종 어순 variants 양방향 매핑 검증 시작")
    print("=" * 80)

    for input_name, brand, expected in HYBRID_TEST_CASES:
        result = resolve_kcar_model_codes(input_name, brand)
        if result == expected:
            print(f"[PASS] {brand:6s} | {input_name:32s} -> {result}")
            passed += 1
        else:
            print(f"[FAIL] {brand:6s} | {input_name:32s} -> 실제: {result}, 기대: {expected}")
            failed += 1

    print("-" * 80)
    print(f"결과: 총 {len(HYBRID_TEST_CASES)}건 중 PASS: {passed}건, FAIL: {failed}건")
    print("=" * 80)
    if failed > 0:
        sys.exit(1)


if __name__ == "__main__":
    test_all_hybrid_variants()
